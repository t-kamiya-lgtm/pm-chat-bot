-- クーポンの対象商品を限定する機能。
-- null または空配列の場合は対象商品の制限なし(全商品に適用可能、従来動作)。
-- 対象商品を指定した場合も、他の条件(最低注文金額・有効期限・上限枚数等)は従来通り適用される。
-- 「カート内の商品のいずれかが対象商品に含まれているか」のゲート条件として使い、
-- 最低注文金額の判定自体は商品代金の合計(amount + addonAmount)全体で行う
-- (対象商品だけの金額ではなく、対象外の商品との合計買いでも成立しうる)。
alter table coupons add column if not exists target_product_ids uuid[];
